using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._EternalWar.Genetics;
using Content.Shared.Humanoid;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._EternalWar.Genetics;

[GenerateTypedNameReferences]
public sealed partial class GenomeScannerWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _proto = default!;

    private static readonly Color InvalidColor = Color.FromHex("#E05050");

    private readonly LineEdit[] _edits = new LineEdit[Genome.BlockCount];

    /// <summary>
    /// What the value means, keyed by the first block of the row.
    /// </summary>
    private readonly Dictionary<GenomeBlock, Label> _meanings = new();
    private readonly Dictionary<GenomeBlock, StyleBoxFlat> _swatches = new();

    /// <summary>
    /// The genome as the server last sent it, for the reset button.
    /// </summary>
    private int[]? _blocks;

    public event Action<int[]>? OnApply;

    public GenomeScannerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        AddValueRow(GenomeBlock.Sentience, "genome-block-sentience");
        AddValueRow(GenomeBlock.Race, "genome-block-race");
        AddValueRow(GenomeBlock.Sex, "genome-block-sex");
        AddColorRow(GenomeBlock.SkinR, "genome-block-skin");
        AddColorRow(GenomeBlock.EyeR, "genome-block-eyes");
        AddColorRow(GenomeBlock.RightEyeR, "genome-block-right-eye");
        AddColorRow(GenomeBlock.HairR, "genome-block-hair");
        AddColorRow(GenomeBlock.BeardR, "genome-block-beard");

        ApplyButton.OnPressed += _ =>
        {
            if (TryRead(out var blocks))
                OnApply?.Invoke(blocks);
        };
        ResetButton.OnPressed += _ => Fill();

        ShowGenome(false);
    }

    public void UpdateState(GenomeScannerBoundUserInterfaceState state)
    {
        TargetLabel.Text = state.Target == null
            ? Loc.GetString("genome-scanner-ui-no-target")
            : Loc.GetString("genome-scanner-ui-target", ("name", state.TargetName));

        _blocks = state.Blocks;
        NoGenomeLabel.Visible = state.Target != null && state.Blocks == null;
        ShowGenome(state.Blocks != null);
        Fill();
    }

    private void ShowGenome(bool visible)
    {
        CodeRow.Visible = visible;
        BlocksGrid.Visible = visible;
        ResetButton.Disabled = !visible;
        ApplyButton.Disabled = !visible;
    }

    private void AddValueRow(GenomeBlock block, string name)
    {
        BlocksGrid.AddChild(new Label { Text = ((int) block + 1).ToString() });
        BlocksGrid.AddChild(new Label { Text = Loc.GetString(name) });
        BlocksGrid.AddChild(MakeEdit(block));

        var meaning = new Label { HorizontalExpand = true };
        _meanings[block] = meaning;
        BlocksGrid.AddChild(meaning);
    }

    private void AddColorRow(GenomeBlock first, string name)
    {
        BlocksGrid.AddChild(new Label { Text = $"{(int) first + 1}–{(int) first + 3}" });
        BlocksGrid.AddChild(new Label { Text = Loc.GetString(name) });

        var edits = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
        for (var i = 0; i < 3; i++)
        {
            edits.AddChild(MakeEdit((GenomeBlock) ((int) first + i)));
        }
        BlocksGrid.AddChild(edits);

        var swatch = new StyleBoxFlat();
        _swatches[first] = swatch;

        var meaning = new Label { HorizontalExpand = true, Margin = new Thickness(6, 0, 0, 0) };
        _meanings[first] = meaning;

        var right = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        right.AddChild(new PanelContainer
        {
            PanelOverride = swatch,
            SetSize = new Vector2(24, 24),
            VerticalAlignment = VAlignment.Center,
        });
        right.AddChild(meaning);
        BlocksGrid.AddChild(right);
    }

    private LineEdit MakeEdit(GenomeBlock block)
    {
        var digits = Genome.Digits(block);
        var edit = new LineEdit
        {
            MinWidth = digits * 14 + 16,
            ToolTip = Loc.GetString("genome-scanner-ui-block-tooltip",
                ("number", (int) block + 1),
                ("max", Genome.Format(block, Genome.MaxValue(block)))),
            // Only as many hex digits as the block holds.
            IsValid = text => text.Length <= digits && text.All(Genome.IsHexDigit),
        };
        edit.OnTextChanged += _ => Refresh();

        _edits[(int) block] = edit;
        return edit;
    }

    private void Fill()
    {
        if (_blocks == null)
            return;

        for (var i = 0; i < Genome.BlockCount; i++)
        {
            _edits[i].Text = Genome.Format((GenomeBlock) i, _blocks[i]);
        }

        Refresh();
    }

    /// <summary>
    /// Explains the values as they are typed and shows the resulting genome code.
    /// </summary>
    private void Refresh()
    {
        RefreshValue(GenomeBlock.Sentience, value => Loc.GetString(Genome.IsSentient(value)
            ? "genome-sentient"
            : "genome-not-sentient"));

        RefreshValue(GenomeBlock.Race, value => Genome.TryGetRace(_proto, value, out var race)
            ? Loc.GetString(race.Name)
            : Loc.GetString("genome-race-unknown"));

        RefreshValue(GenomeBlock.Sex, value => Loc.GetString(Genome.GetSex(value) switch
        {
            Sex.Female => "genome-sex-female",
            Sex.Male => "genome-sex-male",
            _ => "genome-sex-unsexed",
        }));

        foreach (var first in Genome.Colors)
        {
            RefreshColor(first);
        }

        var valid = TryRead(out var blocks);
        ApplyButton.Disabled = !valid || _blocks == null;
        if (valid)
            CodeEdit.Text = Genome.FormatCode(blocks);
    }

    private void RefreshValue(GenomeBlock block, Func<int, string> describe)
    {
        var label = _meanings[block];

        if (Genome.TryParse(block, _edits[(int) block].Text, out var value))
        {
            label.Text = describe(value);
            label.FontColorOverride = null;
        }
        else
        {
            SetInvalid(label, block);
        }
    }

    private void RefreshColor(GenomeBlock first)
    {
        var label = _meanings[first];
        var rgb = new int[3];

        for (var i = 0; i < 3; i++)
        {
            var block = (GenomeBlock) ((int) first + i);
            if (!Genome.TryParse(block, _edits[(int) block].Text, out rgb[i]))
            {
                SetInvalid(label, block);
                _swatches[first].BackgroundColor = Color.Transparent;
                return;
            }
        }

        label.Text = string.Empty;
        _swatches[first].BackgroundColor = new Color(rgb[0] / 255f, rgb[1] / 255f, rgb[2] / 255f);
    }

    private static void SetInvalid(Label label, GenomeBlock block)
    {
        label.Text = Loc.GetString("genome-invalid", ("max", Genome.Format(block, Genome.MaxValue(block))));
        label.FontColorOverride = InvalidColor;
    }

    private bool TryRead(out int[] blocks)
    {
        blocks = new int[Genome.BlockCount];

        for (var i = 0; i < Genome.BlockCount; i++)
        {
            if (!Genome.TryParse((GenomeBlock) i, _edits[i].Text, out blocks[i]))
                return false;
        }

        return true;
    }
}
