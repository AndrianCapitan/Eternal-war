using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared._EternalWar.MindUpload;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._EternalWar.MindUpload;

[GenerateTypedNameReferences]
public sealed partial class MindUploadConsoleWindow : FancyWindow
{
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IGameTiming _timing = default!;

    private readonly SharedMindUploadConsoleSystem _upload;

    private MindUploadConsoleBoundUserInterfaceState? _state;
    private EntityUid? _positronic;

    public event Action? OnUpload;
    public event Action? OnEjectPositronic;
    public event Action? OnEjectSource;

    public MindUploadConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _upload = _entityManager.System<SharedMindUploadConsoleSystem>();

        PositronicView.SpriteOffset = false;
        SourceView.SpriteOffset = false;

        UploadButton.OnPressed += _ => OnUpload?.Invoke();
        EjectPositronicButton.OnPressed += _ => OnEjectPositronic?.Invoke();
        EjectSourceButton.OnPressed += _ => OnEjectSource?.Invoke();
    }

    public void UpdateState(MindUploadConsoleBoundUserInterfaceState state)
    {
        _state = state;
        // The state can arrive before the inserted entities do, treat unknown ones as empty.
        _positronic = GetKnownEntity(state.Positronic);
        var source = GetKnownEntity(state.Source);
        var uploading = state.UploadEnd != null;

        PositronicView.SetEntity(_positronic);
        SourceView.SetEntity(source);
        PositronicName.Text = GetName(_positronic);
        SourceName.Text = GetName(source);

        var positronicFree = _positronic != null && _upload.IsPositronicFree(_positronic.Value);
        PositronicStatus.SetMarkup(Loc.GetString(
            _positronic == null ? "mind-upload-console-ui-positronic-empty"
            : uploading ? "mind-upload-console-ui-positronic-receiving"
            : positronicFree ? "mind-upload-console-ui-positronic-ready"
            : "mind-upload-console-ui-positronic-occupied"));

        SourceStatus.SetMarkup(state.SourceType switch
        {
            MindUploadSourceType.Brain => Loc.GetString(state.SourceHasMind
                ? "mind-upload-console-ui-brain-mind"
                : "mind-upload-console-ui-brain-no-mind"),
            MindUploadSourceType.Pai => Loc.GetString(state.SourceHasMind
                ? "mind-upload-console-ui-pai-mind"
                : "mind-upload-console-ui-pai-no-mind"),
            _ => Loc.GetString("mind-upload-console-ui-source-empty"),
        });

        EjectPositronicButton.Disabled = uploading || _positronic == null;
        EjectSourceButton.Disabled = uploading || source == null;
        UploadButton.Disabled = uploading
                                || !state.Powered
                                || !positronicFree
                                || !state.SourceHasMind;

        UpdateProgress();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_state?.UploadEnd != null)
            UpdateProgress();
    }

    private void UpdateProgress()
    {
        if (_state == null)
            return;

        float progress;
        string status;

        if (_state is { UploadStart: { } start, UploadEnd: { } end })
        {
            var total = (end - start).TotalSeconds;
            var left = Math.Max(0, (end - _timing.CurTime).TotalSeconds);
            progress = total > 0 ? Math.Clamp(1f - (float) (left / total), 0f, 1f) : 1f;
            status = Loc.GetString("mind-upload-console-ui-status-uploading", ("seconds", (int) Math.Ceiling(left)));
        }
        else
        {
            // A positronic brain that already carries a mind is shown as a finished upload.
            var done = _positronic != null && _upload.HasMind(_positronic.Value);
            progress = done ? 1f : 0f;
            status = Loc.GetString(!_state.Powered ? "mind-upload-console-ui-status-no-power"
                : !UploadButton.Disabled ? "mind-upload-console-ui-status-ready"
                : "mind-upload-console-ui-status-idle");
        }

        UploadProgress.Value = progress;
        UploadProgressText.Text = $"{(int) (progress * 100)} %";
        ConsoleStatus.SetMarkup(status);
    }

    private EntityUid? GetKnownEntity(NetEntity? netEntity)
    {
        return _entityManager.TryGetEntity(netEntity, out var uid) && _entityManager.EntityExists(uid) ? uid : null;
    }

    private string GetName(EntityUid? uid)
    {
        return uid == null ? string.Empty : _entityManager.GetComponent<MetaDataComponent>(uid.Value).EntityName;
    }
}
